#region Purpose
// Sample sibling generator: emits one ActionSet (Action plus Handler) per contract in [ContractActions].
#endregion

#region Design
// The Mediator generator cannot see this output. The host declares the same names through
// ContractActionsAttribute, which derives from GeneratedRequestPatternAttribute, so Send has an
// arm for each emitted Action. Each contract has a nested Response and a static Execute method.
// The Action carries the contract; the Handler calls Execute. The transform output is the hint
// name and the rendered text, a value tuple of strings, so the pipeline stays equatable.
#endregion

namespace TimeWarp.Mediator.Examples.GeneratedRequests.Generator;

[Generator]
public sealed class ActionSetGenerator : IIncrementalGenerator
{
  private const string AttributeName = "TimeWarp.Mediator.Examples.GeneratedRequests.ContractActionsAttribute";

  public void Initialize(IncrementalGeneratorInitializationContext context)
  {
    IncrementalValuesProvider<(string HintName, string Source)> hosts = context.SyntaxProvider.ForAttributeWithMetadataName(
        AttributeName,
        static (node, _) => node is ClassDeclarationSyntax,
        static (attributeContext, _) => HostShape.Render(attributeContext));

    context.RegisterSourceOutput(hosts, static (production, host) =>
        production.AddSource(host.HintName, host.Source));
  }

  private static class HostShape
  {
    internal static (string HintName, string Source) Render(GeneratorAttributeSyntaxContext context)
    {
      INamedTypeSymbol host = (INamedTypeSymbol)context.TargetSymbol;
      List<string> contracts = new();
      foreach (AttributeData attribute in context.Attributes)
      {
        foreach (TypedConstant argument in attribute.ConstructorArguments)
        {
          if (argument.Kind != TypedConstantKind.Array)
          {
            continue;
          }

          foreach (TypedConstant value in argument.Values)
          {
            if (value.Value is INamedTypeSymbol contract)
            {
              contracts.Add(contract.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "|" + contract.Name);
            }
          }
        }
      }

      string ns = host.ContainingNamespace.IsGlobalNamespace ? string.Empty : host.ContainingNamespace.ToDisplayString();
      return (host.Name + ".ActionSets.g.cs", Text(ns, host.Name, contracts));
    }

    private static string Text(string ns, string name, List<string> contracts)
    {
      StringBuilder builder = new();
      builder.AppendLine("// <auto-generated/>");
      builder.AppendLine("#nullable enable");
      if (ns.Length > 0)
      {
        builder.Append("namespace ").Append(ns).AppendLine(";");
      }

      builder.Append("partial class ").AppendLine(name);
      builder.AppendLine("{");
      foreach (string entry in contracts)
      {
        string[] parts = entry.Split('|');
        string contract = parts[0];
        string contractName = parts[1];
        builder.Append("    public static class ").Append(contractName).AppendLine("ActionSet");
        builder.AppendLine("    {");
        builder.Append("        public sealed class Action : global::TimeWarp.Mediator.IRequest<").Append(contract).AppendLine(".Response>");
        builder.AppendLine("        {");
        builder.Append("            public Action(").Append(contract).AppendLine(" contract) => Contract = contract;");
        builder.Append("            public ").Append(contract).AppendLine(" Contract { get; }");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.Append("        public sealed class Handler : global::TimeWarp.Mediator.IRequestHandler<Action, ").Append(contract).AppendLine(".Response>");
        builder.AppendLine("        {");
        builder.Append("            public global::System.Threading.Tasks.ValueTask<").Append(contract).AppendLine(".Response> Handle(Action request, global::System.Threading.CancellationToken cancellationToken) =>");
        builder.Append("                global::System.Threading.Tasks.ValueTask.FromResult(").Append(contract).AppendLine(".Execute(request.Contract));");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
      }

      builder.AppendLine("}");
      return builder.ToString();
    }
  }
}
