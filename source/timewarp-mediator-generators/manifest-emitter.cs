#region Purpose
// Emits mediator.manifest.json v2 as the MediatorManifest.Json const (source generators cannot write loose files).
#endregion

#region Design
// Version is 2 because the document has no profile field. A reader that still expects that field
// sees the new version instead of a silent v1. JSON stays the single serialized manifest. The
// same static type exposes Request entries so a host can read kind, response, scope, and the
// ordered behavior list without parsing JSON.
// Requests and each entry's Behaviors are ReadOnlyCollection wrappers over private arrays, so a
// cast cannot mutate the process-wide manifest. Kind precedence matches Nuru's string matcher:
// Query, then IdempotentCommand, then Command, then Action, otherwise Request. Every request
// lists the behaviors the emitter weaves, in that order.
#endregion

namespace TimeWarp.Mediator.Generators;

internal static class ManifestEmitter
{
  internal static void Emit(List<GeneratedSource> sources, EmissionGraph graph)
  {
    string json = BuildJson(graph);
    string ns = graph.GeneratedNamespace;
    StringBuilder builder = new();
    builder.AppendLine("// <auto-generated/>");
    builder.AppendLine("#nullable enable");
    builder.AppendLine();
    builder.Append("namespace ").Append(ns).AppendLine(";");
    builder.AppendLine();
    builder.AppendLine("internal static class MediatorManifest");
    builder.AppendLine("{");
    builder.AppendLine("    public const int Version = 2;");
    builder.AppendLine("    public const string KindAction = \"Action\";");
    builder.AppendLine("    public const string KindCommand = \"Command\";");
    builder.AppendLine("    public const string KindQuery = \"Query\";");
    builder.AppendLine("    public const string KindIdempotentCommand = \"IdempotentCommand\";");
    builder.AppendLine("    public const string KindRequest = \"Request\";");
    builder.AppendLine("    public const string Json =");
    builder.Append("        @\"").Append(json.Replace("\"", "\"\"")).AppendLine("\";");
    builder.AppendLine();
    EmitRequestEntries(builder, graph);
    builder.AppendLine("}");

    sources.Add(new GeneratedSource("MediatorManifest.g.cs", builder.ToString()));
  }

  private static string BuildJson(EmissionGraph graph)
  {
    StringBuilder builder = new();
    builder.Append('{');
    builder.Append("\"version\":2,");
    builder.Append("\"namespace\":\"").Append(Escape(graph.GeneratedNamespace)).Append("\",");
    builder.Append("\"requests\":[");
    for (int i = 0; i < graph.Requests.Length; i++)
    {
      if (i > 0)
      {
        builder.Append(',');
      }

      EmissionRequest request = graph.Requests[i];
      builder.Append('{');
      builder.Append("\"request\":\"").Append(Escape(request.RequestType.Display)).Append("\",");
      builder.Append("\"kind\":\"").Append(Kind(request.RequestType)).Append("\",");
      builder.Append("\"response\":\"").Append(Escape(request.ResponseType.Display)).Append("\",");
      builder.Append("\"handler\":\"").Append(Escape(request.HandlerType.Display)).Append("\",");
      if (request.ScopeType is not null)
      {
        builder.Append("\"scope\":\"").Append(Escape(request.ScopeType.Display)).Append("\",");
      }
      builder.Append("\"behaviors\":[");
      for (int b = 0; b < request.ClosedBehaviors.Length; b++)
      {
        if (b > 0)
        {
          builder.Append(',');
        }

        builder.Append('"').Append(Escape(request.ClosedBehaviors[b].Display)).Append('"');
      }

      builder.Append("]}");
    }

    builder.Append("],\"notifications\":[");
    for (int i = 0; i < graph.Notifications.Length; i++)
    {
      if (i > 0)
      {
        builder.Append(',');
      }

      EmissionNotification notification = graph.Notifications[i];
      builder.Append('{');
      builder.Append("\"notification\":\"").Append(Escape(notification.NotificationType.Display)).Append("\",");
      if (notification.ScopeType is not null)
      {
        builder.Append("\"scope\":\"").Append(Escape(notification.ScopeType.Display)).Append("\",");
      }
      builder.Append("\"handlers\":[");
      for (int h = 0; h < notification.HandlerTypes.Length; h++)
      {
        if (h > 0)
        {
          builder.Append(',');
        }

        builder.Append('"').Append(Escape(notification.HandlerTypes[h].Display)).Append('"');
      }

      builder.Append("]}");
    }

    builder.Append("],\"membership\":[");
    for (int i = 0; i < graph.MemberAssemblyNames.Length; i++)
    {
      if (i > 0)
      {
        builder.Append(',');
      }

      builder.Append('"').Append(Escape(graph.MemberAssemblyNames[i])).Append('"');
    }

    builder.Append("]}");
    return builder.ToString();
  }

  private static void EmitRequestEntries(StringBuilder builder, EmissionGraph graph)
  {
    builder.AppendLine("    private static readonly global::System.Collections.Generic.IReadOnlyList<string> NoBehaviors =");
    builder.AppendLine("        new global::System.Collections.ObjectModel.ReadOnlyCollection<string>(global::System.Array.Empty<string>());");
    builder.AppendLine();
    builder.AppendLine("    private static readonly RequestEntry[] RequestEntries =");
    builder.AppendLine("    [");
    for (int i = 0; i < graph.Requests.Length; i++)
    {
      EmissionRequest request = graph.Requests[i];
      builder.Append("        new RequestEntry(");
      builder.Append(CSharpString(request.RequestType.Display)).Append(", ");
      builder.Append(CSharpString(request.ResponseType.Display)).Append(", ");
      builder.Append(CSharpString(Kind(request.RequestType))).Append(", ");
      if (request.ScopeType is null)
      {
        builder.Append("null, ");
      }
      else
      {
        builder.Append(CSharpString(request.ScopeType.Display)).Append(", ");
      }

      if (request.ClosedBehaviors.Length == 0)
      {
        builder.Append("NoBehaviors");
      }
      else
      {
        builder.Append("new global::System.Collections.ObjectModel.ReadOnlyCollection<string>(new string[] { ");
        for (int b = 0; b < request.ClosedBehaviors.Length; b++)
        {
          if (b > 0)
          {
            builder.Append(", ");
          }

          builder.Append(CSharpString(request.ClosedBehaviors[b].Display));
        }

        builder.Append(" })");
      }

      builder.Append(')');
      if (i + 1 < graph.Requests.Length)
      {
        builder.Append(',');
      }

      builder.AppendLine();
    }

    builder.AppendLine("    ];");
    builder.AppendLine();
    builder.AppendLine("    private static readonly global::System.Collections.ObjectModel.ReadOnlyCollection<RequestEntry> RequestList =");
    builder.AppendLine("        new global::System.Collections.ObjectModel.ReadOnlyCollection<RequestEntry>(RequestEntries);");
    builder.AppendLine();
    builder.AppendLine("    public static global::System.Collections.Generic.IReadOnlyList<RequestEntry> Requests => RequestList;");
    builder.AppendLine();
    builder.AppendLine("    public static RequestEntry Request(string requestType)");
    builder.AppendLine("    {");
    builder.AppendLine("        for (int i = 0; i < RequestEntries.Length; i++)");
    builder.AppendLine("        {");
    builder.AppendLine("            if (string.Equals(RequestEntries[i].Request, requestType, global::System.StringComparison.Ordinal))");
    builder.AppendLine("            {");
    builder.AppendLine("                return RequestEntries[i];");
    builder.AppendLine("            }");
    builder.AppendLine("        }");
    builder.AppendLine();
    builder.AppendLine("        throw new global::System.ArgumentException(\"No manifest entry for '\" + requestType + \"'.\", nameof(requestType));");
    builder.AppendLine("    }");
    builder.AppendLine();
    builder.AppendLine("    public readonly struct RequestEntry");
    builder.AppendLine("    {");
    builder.AppendLine("        public RequestEntry(string request, string response, string kind, string? scope, global::System.Collections.Generic.IReadOnlyList<string> behaviors)");
    builder.AppendLine("        {");
    builder.AppendLine("            Request = request;");
    builder.AppendLine("            Response = response;");
    builder.AppendLine("            Kind = kind;");
    builder.AppendLine("            Scope = scope;");
    builder.AppendLine("            Behaviors = behaviors;");
    builder.AppendLine("        }");
    builder.AppendLine();
    builder.AppendLine("        public string Request { get; }");
    builder.AppendLine();
    builder.AppendLine("        public string Response { get; }");
    builder.AppendLine();
    builder.AppendLine("        public string Kind { get; }");
    builder.AppendLine();
    builder.AppendLine("        public string? Scope { get; }");
    builder.AppendLine();
    builder.AppendLine("        public global::System.Collections.Generic.IReadOnlyList<string> Behaviors { get; }");
    builder.AppendLine("    }");
  }

  // Query, then IdempotentCommand, then Command, then Action. IIdempotentCommand is also ICommand.
  private static string Kind(TypeModel request)
  {
    bool query = false;
    bool idempotentCommand = false;
    bool command = false;
    bool action = false;
    foreach (string name in request.MediatorInterfaceNames)
    {
      if (name == "IQuery")
      {
        query = true;
      }
      else if (name == "IIdempotentCommand")
      {
        idempotentCommand = true;
      }
      else if (name == "ICommand")
      {
        command = true;
      }
      else if (name == "IAction")
      {
        action = true;
      }
    }

    if (query)
    {
      return "Query";
    }

    if (idempotentCommand)
    {
      return "IdempotentCommand";
    }

    if (command)
    {
      return "Command";
    }

    if (action)
    {
      return "Action";
    }

    return "Request";
  }

  private static string CSharpString(string value)
  {
    return "\"" + Escape(value) + "\"";
  }

  private static string Escape(string value)
  {
    return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
  }
}